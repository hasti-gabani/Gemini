"""Derived accounting postings.

Rows here are generated by ledger.posting from source documents (party
opening balances, sales, purchases, payments and bank adjustments). They are
rebuilt whenever a source is saved and cascade-deleted with it, so balances,
statements and reports can never drift from the documents.
"""
from django.db import models
from django.utils import timezone

MONEY = dict(max_digits=14, decimal_places=2, default=0)


class LedgerEntry(models.Model):
    """Party ledger line. debit = party owes us more; credit = party owes us less."""

    TYPE_OPENING = 'opening'
    TYPE_SALE = 'sale'
    TYPE_PURCHASE = 'purchase'
    TYPE_PAYMENT_IN = 'payment_in'
    TYPE_PAYMENT_OUT = 'payment_out'
    TYPE_CHOICES = [
        (TYPE_OPENING, 'Opening Balance'),
        (TYPE_SALE, 'Sale'),
        (TYPE_PURCHASE, 'Purchase'),
        (TYPE_PAYMENT_IN, 'Payment In'),
        (TYPE_PAYMENT_OUT, 'Payment Out'),
    ]

    business = models.ForeignKey('accounts.Business', on_delete=models.CASCADE, related_name='ledger_entries')
    party = models.ForeignKey('parties.Party', on_delete=models.CASCADE, related_name='ledger_entries')
    date = models.DateField()
    entry_type = models.CharField(max_length=12, choices=TYPE_CHOICES)
    number = models.CharField(max_length=40, blank=True)
    description = models.CharField(max_length=255, blank=True)
    items_summary = models.TextField(blank=True)
    qty_summary = models.TextField(blank=True)
    debit = models.DecimalField(**MONEY)
    credit = models.DecimalField(**MONEY)
    sort_order = models.PositiveSmallIntegerField(default=1)
    source_created_at = models.DateTimeField(default=timezone.now)
    sale = models.ForeignKey('transactions.Sale', on_delete=models.CASCADE, null=True, blank=True,
                             related_name='ledger_entries')
    purchase = models.ForeignKey('transactions.Purchase', on_delete=models.CASCADE, null=True, blank=True,
                                 related_name='ledger_entries')
    payment_in = models.ForeignKey('transactions.PaymentIn', on_delete=models.CASCADE, null=True, blank=True,
                                   related_name='ledger_entries')
    payment_out = models.ForeignKey('transactions.PaymentOut', on_delete=models.CASCADE, null=True, blank=True,
                                    related_name='ledger_entries')

    class Meta:
        ordering = ['date', 'sort_order', 'source_created_at', 'id']
        verbose_name_plural = 'ledger entries'
        indexes = [
            models.Index(fields=['party', 'date', 'sort_order']),
            models.Index(fields=['business', 'date']),
        ]

    def __str__(self):
        return f'{self.date} {self.entry_type} {self.number}'


class BankTransaction(models.Model):
    """Cash/bank account movement. amount_in = money received, amount_out = money paid."""

    TYPE_PAYMENT_IN = 'payment_in'
    TYPE_PAYMENT_OUT = 'payment_out'
    TYPE_DEPOSIT = 'deposit'
    TYPE_WITHDRAW = 'withdraw'
    TYPE_TRANSFER_IN = 'transfer_in'
    TYPE_TRANSFER_OUT = 'transfer_out'
    TYPE_ADD = 'add'
    TYPE_REDUCE = 'reduce'
    TYPE_CHOICES = [
        (TYPE_PAYMENT_IN, 'Payment In'),
        (TYPE_PAYMENT_OUT, 'Payment Out'),
        (TYPE_DEPOSIT, 'Deposit'),
        (TYPE_WITHDRAW, 'Withdrawal'),
        (TYPE_TRANSFER_IN, 'Transfer In'),
        (TYPE_TRANSFER_OUT, 'Transfer Out'),
        (TYPE_ADD, 'Money Added'),
        (TYPE_REDUCE, 'Money Reduced'),
    ]

    business = models.ForeignKey('accounts.Business', on_delete=models.CASCADE, related_name='bank_transactions')
    account = models.ForeignKey('banking.BankAccount', on_delete=models.CASCADE, related_name='transactions')
    date = models.DateField()
    txn_type = models.CharField(max_length=12, choices=TYPE_CHOICES)
    number = models.CharField(max_length=40, blank=True)
    description = models.CharField(max_length=255, blank=True)
    reference_no = models.CharField(max_length=80, blank=True)
    amount_in = models.DecimalField(**MONEY)
    amount_out = models.DecimalField(**MONEY)
    party = models.ForeignKey('parties.Party', on_delete=models.SET_NULL, null=True, blank=True,
                              related_name='bank_transactions')
    source_created_at = models.DateTimeField(default=timezone.now)
    payment_in = models.ForeignKey('transactions.PaymentIn', on_delete=models.CASCADE, null=True, blank=True,
                                   related_name='bank_transactions')
    payment_out = models.ForeignKey('transactions.PaymentOut', on_delete=models.CASCADE, null=True, blank=True,
                                    related_name='bank_transactions')
    adjustment = models.ForeignKey('banking.BankAdjustment', on_delete=models.CASCADE, null=True, blank=True,
                                   related_name='bank_transactions')

    class Meta:
        ordering = ['date', 'source_created_at', 'id']
        indexes = [
            models.Index(fields=['account', 'date']),
            models.Index(fields=['business', 'date']),
        ]

    def __str__(self):
        return f'{self.date} {self.txn_type} {self.amount_in or -self.amount_out}'
